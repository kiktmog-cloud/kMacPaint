#!/bin/bash
# ==============================================================================
# kMacPaint macOS .app Bundle Build Script
# Windows 11 mspaint Clean-room Reconstruction for macOS
# ==============================================================================

set -e

APP_NAME="kMacPaint"
BUNDLE_DIR="${APP_NAME}.app"
CONTENTS_DIR="${BUNDLE_DIR}/Contents"
MACOS_DIR="${CONTENTS_DIR}/MacOS"
RESOURCES_DIR="${CONTENTS_DIR}/Resources"

echo "==> 1. Building release binary with Swift Package Manager (Universal ARM64 / x86_64)..."
# Clean up any conflicting dSYM placeholder files created by cloud sync
rm -rf .build/out/Products/Release/*.dSYM 2>/dev/null || true
# Build for Apple Silicon (M1-M5) and Intel
swift build -c release

BIN_PATH=$(swift build -c release --show-bin-path)/${APP_NAME}

echo "==> 2. Creating macOS App Bundle structure..."
rm -rf "${BUNDLE_DIR}"
mkdir -p "${MACOS_DIR}"
mkdir -p "${RESOURCES_DIR}"

echo "==> 3. Copying executable..."
cp "${BIN_PATH}" "${MACOS_DIR}/${APP_NAME}"
chmod +x "${MACOS_DIR}/${APP_NAME}"

# Copy resources bundle if generated by SPM
SPM_BUNDLE=$(swift build -c release --show-bin-path)/${APP_NAME}_${APP_NAME}.bundle
if [ -d "${SPM_BUNDLE}" ]; then
    echo "==> 4. Copying resource bundle..."
    cp -R "${SPM_BUNDLE}" "${RESOURCES_DIR}/"
fi

# Copy AppIcon.icns if exists
ICON_PATH="Sources/kMacPaint/Resources/AppIcon.icns"
if [ -f "${ICON_PATH}" ]; then
    echo "==> 4.1 Copying AppIcon.icns..."
    cp "${ICON_PATH}" "${RESOURCES_DIR}/AppIcon.icns"
fi

echo "==> 5. Generating Info.plist..."
cat <<EOF > "${CONTENTS_DIR}/Info.plist"
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleDevelopmentRegion</key>
    <string>ko</string>
    <key>CFBundleExecutable</key>
    <string>${APP_NAME}</string>
    <key>CFBundleIconFile</key>
    <string>AppIcon</string>
    <key>CFBundleIdentifier</key>
    <string>com.user.kmacpaint</string>
    <key>CFBundleInfoDictionaryVersion</key>
    <string>6.0</string>
    <key>CFBundleName</key>
    <string>${APP_NAME}</string>
    <key>CFBundlePackageType</key>
    <string>APPL</string>
    <key>CFBundleShortVersionString</key>
    <string>1.0.0</string>
    <key>CFBundleVersion</key>
    <string>1</string>
    <key>LSMinimumSystemVersion</key>
    <string>12.0</string>
    <key>NSHighResolutionCapable</key>
    <true/>
    <key>NSPrincipalClass</key>
    <string>NSApplication</string>
</dict>
</plist>
EOF

echo ""
echo "=================================================================="
echo " [SUCCESS] ${APP_NAME}.app 생성이 완료되었습니다!"
echo " 파인더(Finder)에서 '${APP_NAME}.app'을 더블클릭하여 바로 실행하세요."
echo " 배포 시: 우클릭 > 압축하여 '${APP_NAME}.zip'으로 전달하세요."
echo "=================================================================="
